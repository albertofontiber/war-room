/** Convierte una URL pública de Notion a su scheme `notion://` para abrir
 *  la app de escritorio cuando está instalada. Si la URL no es de Notion
 *  (raro), devuelve la original. */
export function toNotionDesktopUrl(url: string): string {
  // Acepta tanto www.notion.so como notion.so directos
  return url.replace(/^https?:\/\/(www\.)?notion\.so\//, "notion://www.notion.so/");
}
